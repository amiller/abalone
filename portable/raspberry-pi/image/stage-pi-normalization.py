#!/usr/bin/env python3
"""Normalize reviewed Pi vendor startup in an exclusive OFFLINE root; dry plan by default."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import stat

RETIRE = frozenset({
    'etc/init.d/resize2fs_once',
    'usr/lib/raspberrypi-sys-mods/firstboot',
    'usr/share/initramfs-tools/scripts/local-premount/firstboot',
    'usr/share/initramfs-tools/scripts/local-bottom/firstboot_fstrim',
    'usr/share/initramfs-tools/scripts/local-bottom/imager_fixup',
})
UNITS = ('userconfig.service', 'sshswitch.service',
         'regenerate_ssh_host_keys.service', 'rpi-eeprom-update.service')
# Generated by systemd-sysv-generator; there is no vendor .service fragment.
GENERATED_MASKS = ('resize2fs_once.service',)
MASK_UNITS = UNITS + GENERATED_MASKS
LINKS = {f'etc/systemd/system/multi-user.target.wants/{u}': f'/lib/systemd/system/{u}'
         for u in UNITS}
LINKS['etc/rc3.d/S01resize2fs_once'] = '../init.d/resize2fs_once'
PACKAGES = ('raspberrypi-sys-mods', 'userconf-pi', 'rpi-eeprom')
FILES = RETIRE | {f'usr/lib/systemd/system/{u}' for u in UNITS} | {
    'boot/firmware/cmdline.txt', 'boot/firmware/config.txt'} | {
    f'var/lib/dpkg/info/{p}.{suffix}' for p in PACKAGES for suffix in ('list', 'md5sums')}
MARKERS = tuple(f'{base}/{name}' for base in ('boot', 'boot/firmware')
                for name in ('firstrun.sh', 'userconf', 'userconf.txt', 'custom.toml', 'ssh', 'ssh.txt'))
BACKUP = 'var/lib/portable-image/retired-vendor-firstboot'
LIMIT = 1024 * 1024


class Refusal(ValueError):
    pass


def need(value, reason):
    if not value:
        raise Refusal(reason)


def sha(body):
    return hashlib.sha256(body).hexdigest()


def encode(value):
    return (json.dumps(value, sort_keys=True, separators=(',', ':')) + '\n').encode()


def bounded(path):
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    try:
        before = os.fstat(fd)
        need(stat.S_ISREG(before.st_mode) and before.st_nlink == 1 and before.st_size <= LIMIT,
             'bounded single regular file required: ' + str(path))
        data = bytearray()
        while True:
            chunk = os.read(fd, min(65536, LIMIT + 1 - len(data)))
            if not chunk:
                break
            data.extend(chunk)
            need(len(data) <= LIMIT, 'input grew beyond bound')
        after = os.fstat(fd)
        need((before.st_size, before.st_mtime_ns, before.st_ctime_ns) ==
             (after.st_size, after.st_mtime_ns, after.st_ctime_ns) and len(data) == before.st_size,
             'input changed while reading')
        return bytes(data)
    finally:
        os.close(fd)


def safe(root, name, kind='file'):
    path = root / name
    need(path.is_relative_to(root), 'outside offline root')
    for parent in reversed((path.parent, *path.parent.parents)):
        if parent == root or parent.is_relative_to(root):
            if parent.exists() or parent.is_symlink():
                s = parent.lstat()
                need(stat.S_ISDIR(s.st_mode) and s.st_uid in (0, os.getuid()) and
                     not s.st_mode & 0o022, 'unsafe directory: ' + str(parent))
    if path.exists() or path.is_symlink():
        s = path.lstat()
        check = {'file': stat.S_ISREG, 'link': stat.S_ISLNK, 'directory': stat.S_ISDIR}[kind]
        need(check(s.st_mode) and s.st_uid in (0, os.getuid()) and
             (kind == 'link' or not s.st_mode & 0o022) and
             (kind != 'file' or s.st_nlink == 1), 'unsafe input/output: ' + name)
    return path


def load_profile(path, pin):
    raw = bounded(path)
    need(sha(raw) == pin, 'profile digest mismatch')
    def pairs(items):
        result = {}
        for key, value in items:
            need(key not in result, 'duplicate profile key')
            result[key] = value
        return result
    value = json.loads(raw, object_pairs_hook=pairs)
    need(set(value) == {'version', 'files', 'links', 'provenance'} and
         type(value['version']) is int and value['version'] == 1 and
         isinstance(value['files'], dict) and set(value['files']) == FILES and
         value['links'] == LINKS and isinstance(value['provenance'], dict),
         'profile must bind the exact supported Pi paths')
    for record in value['files'].values():
        need(isinstance(record, dict) and set(record) == {'sha256', 'mode'} and
             isinstance(record['sha256'], str) and len(record['sha256']) == 64 and
             type(record['mode']) is int and record['mode'] in (0o644, 0o755), 'invalid input record')
    return value, raw


def cmdline(body):
    text = body.decode('ascii')
    need('\0' not in text and len(text.splitlines()) <= 2, 'unsupported cmdline')
    tokens = text.split()
    remove = {'init=/usr/lib/raspberrypi-sys-mods/firstboot', 'fsck.repair=yes'}
    need(all(tokens.count(t) == 1 for t in remove), 'exact original startup triggers required')
    result = [t for t in tokens if t not in remove]
    need(not any(t.startswith(('init=', 'rdinit=', 'systemd.run', 'fsck.repair=')) or
                 'firstboot' in t or 'firstrun' in t for t in result), 'unreviewed cmdline startup override')
    need(sum(t.startswith('root=') for t in result) == 1 and 'rootfstype=ext4' in result,
         'ambiguous root selection')
    return (' '.join(result) + '\n').encode()


def build(root, profile, profile_raw):
    need(root.is_absolute() and root.is_dir() and root.resolve() == root and
         not os.path.samefile(root, '/'), 'canonical exclusive offline root required')
    backup = safe(root, BACKUP, 'directory')
    need(not backup.exists(), 'normalization already attempted; preserve partial tree, no replay')
    inputs = {}
    for name, record in profile['files'].items():
        path = safe(root, name)
        body = bounded(path)
        need(sha(body) == record['sha256'] and stat.S_IMODE(path.stat().st_mode) == record['mode'],
             'unreviewed vendor bytes/mode: ' + name)
        inputs[name] = body
    for name, target in LINKS.items():
        path = safe(root, name, 'link')
        need(path.is_symlink() and os.readlink(path) == target, 'unreviewed enabled unit link: ' + name)
    for unit in MASK_UNITS:
        path = safe(root, 'etc/systemd/system/' + unit)
        need(not path.exists() and not path.is_symlink(), 'existing vendor unit override/mask')
        dropin = safe(root, 'etc/systemd/system/' + unit + '.d', 'directory')
        need(not dropin.exists() or not list(dropin.iterdir()), 'unreviewed vendor unit drop-ins')
    for base in ('usr/lib/systemd/system', 'run/systemd/system'):
        for unit in MASK_UNITS:
            directory = safe(root, base + '/' + unit + '.d', 'directory')
            need(not directory.exists() or not list(directory.iterdir()), 'unreviewed vendor unit drop-ins')
            if base.startswith('run/'):
                p = root / base / unit
                need(not p.exists() and not p.is_symlink(), 'runtime vendor unit override')
    system = root / 'etc/systemd/system'
    for parent, dirs, names in os.walk(system, followlinks=False):
        for leaf in dirs + names:
            p = Path(parent) / leaf
            if p.is_symlink() and Path(os.readlink(p)).name in MASK_UNITS:
                need(p.relative_to(root).as_posix() in LINKS, 'unreviewed vendor activation link')
    # Bind all SysV activations of the reviewed unowned vendor script.
    for runlevel in ('S', '0', '1', '2', '3', '4', '5', '6'):
        directory = safe(root, 'etc/rc' + runlevel + '.d', 'directory')
        if not directory.exists():
            continue
        for path in directory.iterdir():
            is_activation = path.name.endswith('resize2fs_once') or (
                path.is_symlink() and Path(os.readlink(path)).name == 'resize2fs_once')
            if is_activation:
                need(path.relative_to(root).as_posix() in LINKS and path.is_symlink() and
                     os.readlink(path) == LINKS[path.relative_to(root).as_posix()],
                     'unreviewed resize activation: ' + str(path))
    for name in MARKERS:
        path = root / name
        safe(root, str(Path(name).parent), 'directory')
        need(not path.exists() and not path.is_symlink(), 'personalization/startup marker needs separate review: ' + name)
    # The network installer owns NetworkManager migration. Do not parse or silently
    # remove arbitrary YAML (which could contain network credentials).
    lib = root / 'lib'
    if lib.is_symlink():
        need(os.readlink(lib) == 'usr/lib' and lib.resolve() == root / 'usr/lib',
             'unsupported lib alias')
    elif lib.exists():
        path = safe(root, 'lib/netplan', 'directory')
        need(not path.exists() or not list(path.iterdir()), 'netplan input needs explicit separate normalization')
    for name in ('etc/netplan', 'run/netplan', 'usr/lib/netplan'):
        path = safe(root, name, 'directory')
        need(not path.exists() or not list(path.iterdir()), 'netplan input needs explicit separate normalization')
    # Review executable hook names, not unrelated prose containing "firstboot".
    for name in ('usr/share/initramfs-tools/scripts', 'etc/initramfs-tools/scripts',
                 'usr/lib/raspberrypi-sys-mods'):
        directory = safe(root, name, 'directory')
        if not directory.exists():
            continue
        for parent, dirs, names in os.walk(directory, followlinks=False):
            for leaf in dirs + names:
                p = Path(parent) / leaf
                executable = p.is_symlink() or (p.is_file() and p.stat().st_mode & 0o111)
                if executable and any(word in leaf for word in ('firstboot', 'firstrun', 'imager_fixup')):
                    need(p.relative_to(root).as_posix() in RETIRE, 'unknown vendor startup path: ' + str(p))
    updated = cmdline(inputs['boot/firmware/cmdline.txt'])
    plan = {'version': 1, 'root': str(root), 'rootIdentity': [root.stat().st_dev, root.stat().st_ino],
            'sourceSha256': sha(Path(__file__).read_bytes()), 'profileSha256': sha(profile_raw),
            'inputFiles': profile['files'], 'retireFiles': sorted(RETIRE), 'retireLinks': LINKS,
            'maskUnits': list(MASK_UNITS), 'cmdlineBefore': sha(inputs['boot/firmware/cmdline.txt']),
            'cmdlineAfter': sha(updated), 'backup': BACKUP,
            'preservedFirmwareConfig': profile['files']['boot/firmware/config.txt']['sha256']}
    return plan, inputs, updated


def directories(root, path):
    safe(root, str(path.relative_to(root)) + '/.path-check')
    missing = []
    while not path.exists():
        missing.append(path)
        path = path.parent
    for p in reversed(missing):
        p.mkdir(mode=0o700)
        os.chown(p, 0, 0)
        os.chmod(p, 0o755)
        for directory in (p, p.parent):
            fd = os.open(directory, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
            try:
                os.fsync(fd)
            finally:
                os.close(fd)


def write_new(root, name, body, mode):
    path = safe(root, name)
    directories(root, path.parent)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    try:
        with os.fdopen(os.dup(fd), 'wb') as stream:
            stream.write(body)
            stream.flush()
        os.fchmod(fd, mode)
        os.fchown(fd, 0, 0)
        os.fsync(fd)
    finally:
        os.close(fd)
    directory = os.open(path.parent, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
    try:
        os.fsync(directory)
    finally:
        os.close(directory)


def apply(root, plan, inputs, updated, profile_raw):
    # Backup/intent is outside every initramfs, systemd, boot and generator path.
    # It is created first, so interruption cannot masquerade as a pristine retry.
    write_new(root, BACKUP + '/intent.json', encode(plan), 0o600)
    write_new(root, BACKUP + '/profile.json', profile_raw, 0o600)
    for name, body in inputs.items():
        write_new(root, BACKUP + '/original/' + name, body, 0o600)
    write_new(root, BACKUP + '/links.json', encode(LINKS), 0o600)
    for name in RETIRE:
        safe(root, name).unlink()
    for name in LINKS:
        safe(root, name, 'link').unlink()
    for unit in MASK_UNITS:
        path = safe(root, 'etc/systemd/system/' + unit)
        path.symlink_to('/dev/null')
    name = 'boot/firmware/cmdline.txt'
    write_new(root, name + '.portable-normalization-new', updated, inputs_mode(plan, name))
    os.replace(root / (name + '.portable-normalization-new'), root / name)
    changed_parents = {str(Path(n).parent) for n in RETIRE | set(LINKS)} | {
        'etc/systemd/system', 'boot/firmware'}
    for name in sorted(changed_parents):
        fd = os.open(root / name, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
        try:
            os.fsync(fd)
        finally:
            os.close(fd)
    write_new(root, BACKUP + '/completed.json', encode({'planSha256': sha(encode(plan)),
              'qualification': 'offline vendor normalization only; generated initramfs and boot unqualified'}), 0o600)


def inputs_mode(plan, name):
    return plan['inputFiles'][name]['mode']


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, required=True)
    parser.add_argument('--profile', type=Path, required=True)
    parser.add_argument('--profile-sha256', required=True)
    parser.add_argument('--apply', action='store_true')
    parser.add_argument('--plan-sha256')
    args = parser.parse_args()
    profile, raw = load_profile(args.profile, args.profile_sha256)
    plan, inputs, updated = build(args.root, profile, raw)
    digest = sha(encode(plan))
    if args.apply:
        need(os.getuid() == 0 and args.plan_sha256 == digest, 'root and exact reviewed plan digest required')
        apply(args.root, plan, inputs, updated, raw)
    print(json.dumps({'applied': args.apply, 'planSha256': digest, 'plan': plan}, indent=2))


if __name__ == '__main__':
    try:
        main()
    except (Refusal, OSError, ValueError) as error:
        raise SystemExit('REFUSED: ' + str(error))
