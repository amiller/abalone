import base64
import importlib.util
import json
from pathlib import Path
import struct
import unittest

spec = importlib.util.spec_from_file_location('personalize', Path(__file__).with_name('personalize.py'))
p = importlib.util.module_from_spec(spec)
spec.loader.exec_module(p)

class PersonalizationTests(unittest.TestCase):
    def wifi(self, **kwargs):
        value = dict(version=1, keyManagement='wpa-psk', ssid='demo-network', psk='practice123')
        value.update(kwargs)
        return json.dumps(value).encode()

    def test_wifi_encoded_not_interpreted(self):
        config = p.wifi_config(self.wifi(ssid='x"\nnetwork={'))
        self.assertNotIn('x"', config)
        self.assertEqual(config.count('network={'), 1)
        self.assertRegex(config, r'psk=[0-9a-f]{64}\n')
        self.assertNotIn('practice123', config)

    def test_wifi_schema_and_bounds(self):
        for raw in (self.wifi(version=True), self.wifi(ssid='a'*33), self.wifi(psk='short'), self.wifi(keyManagement='open'), self.wifi(extra='x'), b'{"version":1,"version":1}'):
            with self.assertRaises((ValueError, KeyError)):
                p.wifi_config(raw)
        self.assertIn('psk=' + 'a'*64, p.wifi_config(self.wifi(psk='a'*64)))

    def test_keys_canonical_no_injected_options(self):
        blob = struct.pack('>I',11)+b'ssh-ed25519'+struct.pack('>I',32)+b'a'*32
        key = 'ssh-ed25519 ' + base64.b64encode(blob).decode()
        self.assertEqual(p.public_keys((key+' comment\n'+key+'\n').encode()), key+'\n')
        for text in ('command="evil" '+key, 'ssh-rsa AA==', 'ssh-ed25519 AA=='):
            with self.assertRaises(ValueError): p.public_keys(text.encode())

    def test_admin_no_vault_dependency_no_forwarding(self):
        self.assertNotIn('vault', p.SSH_UNIT)
        self.assertIn('Requires=tor-guest-firewall.service', p.SSH_UNIT)
        for line in ('AllowUsers root', 'PasswordAuthentication no', 'AuthenticationMethods publickey', 'AllowTcpForwarding no', 'AllowAgentForwarding no', 'PermitRootLogin prohibit-password'):
            self.assertIn(line, p.SSHD)
        self.assertNotIn('Include', p.SSHD)
        self.assertNotIn('StandardOutput=null', p.WIFI_UNIT)
        self.assertNotIn(' -d', p.WIFI_UNIT)
        self.assertIn('DHCP=ipv4', p.NETWORK)
        self.assertIn('ExecStartPre=/usr/sbin/rfkill unblock wifi', p.WIFI_UNIT)


class PayloadBuilderTests(unittest.TestCase):
    def test_actual_private_payload_modes_links_and_unique_hostkey(self):
        import tempfile, os, sys, hashlib
        sys.path.insert(0, str(Path(__file__).parent))
        import build_payload
        # Self-contained synthetic policy input: the builder's contract binds exact
        # generated bytes by hash, kernel enforcement is tested separately.
        import subprocess, shutil
        text = subprocess.check_output([shutil.which('node'), str(Path(__file__).with_name('render-policy.mjs')), '105', '998']).decode('utf-8')
        self.assertIn('—', text)
        with tempfile.TemporaryDirectory() as d:
            root = Path(d)
            root.chmod(0o700)
            wf = root/'wifi'; wf.write_bytes(json.dumps(dict(version=1,keyManagement='wpa-psk',ssid='SYNTHETIC',psk='synthetic123')).encode()); wf.chmod(0o600)
            blob = struct.pack('>I',11)+b'ssh-ed25519'+struct.pack('>I',32)+b'a'*32
            kf = root/'keys'; kf.write_text('ssh-ed25519 '+base64.b64encode(blob).decode()); kf.chmod(0o600)
            nf=root/'policy'; nf.write_text(text);nf.chmod(0o644)
            out=root/'payload'
            manifest=build_payload.build(out,wf,kf,nf,hashlib.sha256(text.encode()).hexdigest())
            self.assertEqual(len(manifest['files']),10)
            self.assertEqual(len(manifest['symlinks']),2)
            self.assertEqual(out.stat().st_mode&0o777,0o700)
            for target,value in manifest['files'].items():
                self.assertEqual(value['uid'],0)
                path=out/value['source']
                self.assertEqual(path.stat().st_mode&0o777,0o600)
                self.assertEqual(hashlib.sha256(path.read_bytes()).hexdigest(),value['sha256'])
            self.assertTrue((out/'host-ed25519').read_bytes().startswith(b'-----BEGIN OPENSSH PRIVATE KEY-----'))
            with self.assertRaises(ValueError):build_payload.build(out,wf,kf,nf,hashlib.sha256(text.encode()).hexdigest())
            with self.assertRaises(ValueError):build_payload.build(root/'other',wf,kf,nf,'0'*64)

if __name__ == '__main__': unittest.main()
